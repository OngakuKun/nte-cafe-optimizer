#!/usr/bin/env python3
"""Generate the embedded fallback header from data/gamedata.json.

Usage: python3 scripts/embed_gamedata.py
The generated header is checked in so builds need no Python.
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
source = root / 'data' / 'gamedata.json'
target = root / 'lib' / 'nte_cafe' / 'include' / 'gamedata_embedded.h'

text = source.read_text(encoding='utf-8')
json.loads(text)  # fail fast on invalid JSON

lines = text.splitlines(keepends=True)


def c_escape(line):
    out = []
    for ch in line:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        else:
            out.append(ch)
    return ''.join(out)


body = ' \\\n'.join(f'  "{c_escape(line)}"' for line in lines)
header = f"""/* Generated by scripts/embed_gamedata.py — do not edit by hand. */
#ifndef NTE_CAFE_GAMEDATA_EMBEDDED_H
#define NTE_CAFE_GAMEDATA_EMBEDDED_H

#define GAMEDATA_EMBEDDED_JSON \\
{body}

#endif /* NTE_CAFE_GAMEDATA_EMBEDDED_H */
"""
target.write_text(header, encoding='utf-8')
print(f'{target.relative_to(root)}: {len(text)} bytes embedded')
